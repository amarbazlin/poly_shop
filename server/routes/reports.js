const router = express.Router()

const getSupabase = (req) => {
  const token = req.headers.authorization?.split(' ')[1] || ''
  // If no token or empty token, use service client (bypasses RLS for reports)
  if (!token) return getServiceClient()
  return createUserClient(token)
}

// ── Helpers ──────────────────────────────────────────────────────────────────

const STOCK_STATUS = {
  OUT_OF_STOCK: 'out_of_stock',
  CRITICAL:     'critical',
  LOW:          'low',
  NORMAL:       'normal',
  OVERSTOCKED:  'overstocked',
}

function getStockStatus(quantity, reorderLevel) {
  if (quantity === 0)                           return STOCK_STATUS.OUT_OF_STOCK
  if (quantity <= reorderLevel * 0.5)           return STOCK_STATUS.CRITICAL
  if (quantity <= reorderLevel)                 return STOCK_STATUS.LOW
  if (quantity >= reorderLevel * 5)             return STOCK_STATUS.OVERSTOCKED
  return STOCK_STATUS.NORMAL
}

function formatDate(d) {
  if (!d) return '—'
  return new Date(d).toLocaleDateString('en-LK', { year: 'numeric', month: 'short', day: 'numeric' })
}

function formatCurrency(amount) {
  if (amount == null) return '—'
  return `Rs. ${Number(amount).toLocaleString('en-LK', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
}

function getDateRange(dateFrom, dateTo) {
  const from = dateFrom ? new Date(dateFrom) : new Date(Date.now() - 90 * 86400000)
  const to = dateTo ? new Date(dateTo) : new Date()
  return { from: from.toISOString(), to: to.toISOString() }
}

// ── PDF helpers ─────────────────────────────────────────────────────────────

function addReportHeader(doc, title, dateRangeText, businessName = 'Forgera') {
  const DARK = [13, 17, 23]
  const ACCENT = [249, 115, 22]

  doc.setFillColor(...DARK)
  doc.rect(0, 0, 210, 38, 'F')

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  doc.setTextColor(255, 255, 255)
  doc.text(businessName || 'Forgera', 14, 16)

  doc.setFillColor(...ACCENT)
  doc.roundedRect(120, 6, 76, 10, 2, 2, 'F')
  doc.setFontSize(9)
  doc.text(title, 158, 12.5, { align: 'center' })

  doc.setFontSize(7.5)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(180, 180, 180)
  doc.text(businessName ? `${businessName} — Report` : 'Forgera OS — Report', 14, 24)

  doc.setTextColor(180, 180, 180)
  doc.setFontSize(8)
  doc.text(dateRangeText, 196, 24, { align: 'right' })

  doc.setTextColor(180, 180, 180)
  doc.setFontSize(7)
  doc.text(`Generated: ${new Date().toLocaleString('en-LK')}`, 196, 30, { align: 'right' })

  doc.setFillColor(...ACCENT)
  doc.rect(0, 38, 210, 1.5, 'F')
}

function addReportFooter(doc) {
  const DARK = [13, 17, 23]
  doc.setFillColor(...DARK)
  doc.rect(0, 285, 210, 12, 'F')
  doc.setFontSize(6.5)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(180, 180, 180)
  doc.text('Generated by Forgera OS', 14, 292)
  doc.text(new Date().toISOString(), 196, 292, { align: 'right' })
}

function addKpiCards(doc, kpis, startY) {
  const cardW = 44
  const cardH = 18
  const gap = 4
  const left = 14
  let y = startY

  kpis.forEach((kpi, i) => {
    const x = left + i * (cardW + gap)
    doc.setFillColor(245, 245, 245)
    doc.roundedRect(x, y, cardW, cardH, 2, 2, 'F')
    doc.setFontSize(6.5)
    doc.setFont('helvetica', 'bold')
    doc.setTextColor(100, 100, 100)
    doc.text(kpi.label, x + 4, y + 6)
    doc.setFontSize(9)
    doc.setFont('helvetica', 'bold')
    doc.setTextColor(13, 17, 23)
    doc.text(kpi.value, x + 4, y + 14)
  })

  return y + cardH + 6
}

// ── Excel helpers ────────────────────────────────────────────────────────────

async function buildWorkbook(summaryRows, detailHeaders, detailRows, sheetName = 'Report') {
  const wb = new ExcelJS.Workbook()
  wb.creator = 'Forgera OS'
  wb.created = new Date()

  const summarySheet = wb.addWorksheet('Summary')
  summarySheet.columns = [
    { header: 'Metric', key: 'label', width: 30 },
    { header: 'Value', key: 'value', width: 20 },
  ]
  summarySheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } }
  summarySheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF0D1117' } }
  summaryRows.forEach((r, i) => {
    summarySheet.getRow(i + 2).getCell(1).value = r.label
    summarySheet.getRow(i + 2).getCell(2).value = r.value
  })

  const detailSheet = wb.addWorksheet(sheetName)
  detailSheet.columns = detailHeaders.map(h => ({ header: h, key: h.replace(/\s+/g, '_').toLowerCase(), width: 20 }))
  detailSheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } }
  detailSheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF0D1117' } }

  detailRows.forEach((row, i) => {
    const r = detailSheet.getRow(i + 2)
    row.forEach((val, j) => {
      r.getCell(j + 1).value = val
      if (typeof val === 'number' && detailHeaders[j]?.toLowerCase().includes('value') || detailHeaders[j]?.toLowerCase().includes('amount') || detailHeaders[j]?.toLowerCase().includes('cost') || detailHeaders[j]?.toLowerCase().includes('price') || detailHeaders[j]?.toLowerCase().includes('revenue') || detailHeaders[j]?.toLowerCase().includes('subtotal')) {
        r.getCell(j + 1).numFmt = 'Rs. #,##0.00'
      }
    })
  })

  return wb
}

