// GET /api/reports/inventory?location_id=&format=json|pdf|excel
// ═════════════════════════════════════════════════════════════════════════════
router.get('/inventory', async (req, res) => {
  const supabase = getSupabase(req)
  const { location_id, format = 'json' } = req.query

  try {
    let query = supabase
      .from('products')
      .select(`
        id, product_name, product_code, quantity, reorder_level,
        cost_price, selling_price, unit, status,
        category:category_id ( name )
      `)
      .eq('status', 'active')

    if (req.businessId) query = query.eq('business_id', req.businessId)

    if (location_id) {
      query = supabase
        .from('location_stock')
        .select(`
          quantity,
          product:product_id (
            id, product_name, product_code, reorder_level,
            cost_price, selling_price, unit, status,
            category:category_id ( name )
          )
        `)
        .eq('location_id', location_id)
    }

    const { data, error } = await query
    if (error) throw error

    let products
    if (location_id) {
      products = data.map(ls => ({
        ...ls.product,
        quantity: ls.quantity,
      })).filter(p => p.status === 'active')
    } else {
      products = data || []
    }

    const stockLevels = products.map(p => {
      const qty = Number(p.quantity) || 0
      const reorder = Number(p.reorder_level) || 0
      return {
        id: p.id,
        product_name: p.product_name,
        product_code: p.product_code,
        quantity: qty,
        reorder_level: reorder,
        cost_price: Number(p.cost_price) || 0,
        selling_price: Number(p.selling_price) || 0,
        unit: p.unit,
        category: p.category?.name || 'Uncategorized',
        status: getStockStatus(qty, reorder),
      }
    })

    // Sort by tied-up value (qty * cost_price) descending for "highest value tied up"
    const stockByValue = [...stockLevels].sort((a, b) => (b.quantity * b.cost_price) - (a.quantity * a.cost_price))

    const totalStockValueCost = stockLevels.reduce((s, p) => s + p.quantity * p.cost_price, 0)
    const totalStockValueRetail = stockLevels.reduce((s, p) => s + p.quantity * p.selling_price, 0)
    const totalProducts = stockLevels.length
    const totalUnits = stockLevels.reduce((s, p) => s + p.quantity, 0)

    // Category breakdown with both cost and retail values
    const byCategory = {}
    stockLevels.forEach(p => {
      if (!byCategory[p.category]) byCategory[p.category] = { product_count: 0, total_stock: 0, value_cost_lkr: 0, value_retail_lkr: 0 }
      byCategory[p.category].product_count += 1
      byCategory[p.category].total_stock += p.quantity
      byCategory[p.category].value_cost_lkr += p.quantity * p.cost_price
      byCategory[p.category].value_retail_lkr += p.quantity * p.selling_price
    })

    const categoryBreakdown = Object.entries(byCategory)
      .map(([name, data]) => ({ name, ...data }))
      .sort((a, b) => b.value_cost_lkr - a.value_cost_lkr)

    // Status counts
    const statusCounts = {
      healthy: stockLevels.filter(p => p.status === STOCK_STATUS.NORMAL).length,
      low: stockLevels.filter(p => p.status === STOCK_STATUS.LOW).length,
      critical: stockLevels.filter(p => p.status === STOCK_STATUS.CRITICAL).length,
      out_of_stock: stockLevels.filter(p => p.status === STOCK_STATUS.OUT_OF_STOCK).length,
      overstocked: stockLevels.filter(p => p.status === STOCK_STATUS.OVERSTOCKED).length,
    }

    const reportData = {
      generated_at: new Date().toISOString(),
      total_products: totalProducts,
      total_stock_units: totalUnits,
      total_stock_value_at_cost_lkr: Math.round(totalStockValueCost * 100) / 100,
      total_stock_value_at_retail_lkr: Math.round(totalStockValueRetail * 100) / 100,
      status_summary: statusCounts,
      category_breakdown: categoryBreakdown,
      stock_levels: stockLevels,
      top_tied_up_stock: stockByValue.slice(0, 10).map(p => ({
        id: p.id,
        product_name: p.product_name,
        product_code: p.product_code,
        quantity: p.quantity,
        cost_price: p.cost_price,
        selling_price: p.selling_price,
        tied_up_value_lkr: Math.round(p.quantity * p.cost_price * 100) / 100,
        category: p.category,
      })),
    }

    if (format === 'pdf') {
      const doc = new jsPDF({ unit: 'mm', format: 'a4' })
      addReportHeader(doc, 'INVENTORY REPORT', 'Current snapshot')
      let y = addKpiCards(doc, [
        { label: 'Total Products', value: String(totalProducts) },
        { label: 'Total Units', value: String(totalUnits) },
        { label: 'Value (Cost)', value: formatCurrency(totalStockValueCost) },
        { label: 'Value (Retail)', value: formatCurrency(totalStockValueRetail) },
      ], 46)

      // Status summary
      doc.setFontSize(8)
      doc.setFont('helvetica', 'bold')
      doc.setTextColor(13, 17, 23)
      doc.text('Stock Health Summary', 14, y)
      y += 4
      const statusLabels = [
        { label: 'Healthy', count: statusCounts.healthy, color: '#22c55e' },
        { label: 'Low', count: statusCounts.low, color: '#f59e0b' },
        { label: 'Critical', count: statusCounts.critical, color: '#ef4444' },
        { label: 'Out of Stock', count: statusCounts.out_of_stock, color: '#9ca3af' },
        { label: 'Overstocked', count: statusCounts.overstocked, color: '#3b82f6' },
      ]
      statusLabels.forEach((s, i) => {
        const x = 14 + i * 38
        doc.setFillColor(245, 245, 245)
        doc.roundedRect(x, y, 36, 10, 2, 2, 'F')
        doc.setFontSize(6.5)
        doc.setFont('helvetica', 'normal')
        doc.setTextColor(100, 100, 100)
        doc.text(s.label, x + 3, y + 4)
        doc.setFontSize(9)
        doc.setFont('helvetica', 'bold')
        doc.setTextColor(13, 17, 23)
        doc.text(String(s.count), x + 3, y + 9)
      })
      y += 16

      const tableRows = stockLevels.map((p, i) => [
        i + 1,
        p.product_name,
        p.product_code || '—',
        p.category,
        p.quantity,
        p.reorder_level,
        p.status.replace(/_/g, ' '),
        formatCurrency(p.quantity * p.cost_price),
      ])

      doc.autoTable({
        startY: y,
        margin: { left: 14, right: 14 },
        head: [['#', 'Product', 'SKU', 'Category', 'Qty', 'Reorder', 'Status', 'Value (Cost)']],
        body: tableRows,
        headStyles: { fillColor: [13, 17, 23], textColor: 255, fontSize: 7, fontStyle: 'bold', halign: 'center' },
        columnStyles: {
          0: { cellWidth: 8, halign: 'center' },
          1: { cellWidth: 40 },
          2: { cellWidth: 18 },
          3: { cellWidth: 25 },
          4: { cellWidth: 12, halign: 'center' },
          5: { cellWidth: 14, halign: 'center' },
          6: { cellWidth: 22, halign: 'center' },
          7: { cellWidth: 25, halign: 'right' },
        },
        bodyStyles: { fontSize: 7, textColor: [40, 40, 40] },
        alternateRowStyles: { fillColor: [250, 250, 250] },
        styles: { lineColor: [220, 220, 220], lineWidth: 0.1 },
      })

      addReportFooter(doc)
      const buf = Buffer.from(doc.output('arraybuffer'))
      res.setHeader('Content-Type', 'application/pdf')
      res.setHeader('Content-Disposition', `attachment; filename="forgera-inventory-report-${new Date().toISOString().slice(0, 10)}.pdf"`)
      return res.send(buf)
    }

    if (format === 'excel') {
      const summaryRows = [
        { label: 'Total Products', value: totalProducts },
        { label: 'Total Stock Units', value: totalUnits },
        { label: 'Total Stock Value (Cost)', value: totalStockValueCost },
        { label: 'Total Stock Value (Retail)', value: totalStockValueRetail },
        { label: 'Healthy Products', value: statusCounts.healthy },
        { label: 'Low Stock', value: statusCounts.low },
        { label: 'Critical', value: statusCounts.critical },
        { label: 'Out of Stock', value: statusCounts.out_of_stock },
        { label: 'Overstocked', value: statusCounts.overstocked },
      ]
      const detailHeaders = ['#', 'Product', 'SKU', 'Category', 'Quantity', 'Reorder Level', 'Status', 'Value (Cost)']
      const detailRows = stockLevels.map((p, i) => [
        i + 1, p.product_name, p.product_code || '—', p.category,
        p.quantity, p.reorder_level, p.status.replace(/_/g, ' '),
        Math.round(p.quantity * p.cost_price * 100) / 100,
      ])

      const wb = await buildWorkbook(summaryRows, detailHeaders, detailRows, 'Inventory')
      const buf = await wb.xlsx.writeBuffer()
      res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet')
      res.setHeader('Content-Disposition', `attachment; filename="forgera-inventory-report-${new Date().toISOString().slice(0, 10)}.xlsx"`)
      return res.send(Buffer.from(buf))
    }

    res.json(reportData)
  } catch (err) {
    console.error('Error generating inventory report:', err)
    res.status(500).json({ error: err.message })
  }
})

