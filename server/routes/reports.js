// GET /api/reports/suppliers?date_from=&date_to=&format=json|pdf|excel
// ═════════════════════════════════════════════════════════════════════════════
router.get('/suppliers', async (req, res) => {
  const supabase = getSupabase(req)
  const { date_from, date_to, format = 'json' } = req.query
  const { from, to } = getDateRange(date_from, date_to)

  try {
    let suppliersQuery = supabase
      .from('suppliers')
      .select('id, supplier_name, average_delivery_days, status')
      .eq('status', 'active')

    if (req.businessId) suppliersQuery = suppliersQuery.eq('business_id', req.businessId)

    const { data: suppliers, error: supErr } = await suppliersQuery
    if (supErr) throw supErr

    let purchasesQuery = supabase
      .from('purchases')
      .select(`
        id, supplier_id, total_amount, status, created_at,
        expected_delivery_date, received_at
      `)
      .gte('created_at', from)
      .lte('created_at', to)

    if (req.businessId) purchasesQuery = purchasesQuery.eq('business_id', req.businessId)

    const { data: purchases, error: purchErr } = await purchasesQuery
    if (purchErr) throw purchErr

    const supplierMap = {}
    suppliers.forEach(s => {
      supplierMap[s.id] = {
        supplier_id: s.id,
        supplier_name: s.supplier_name,
        average_delivery_days: s.average_delivery_days,
        total_purchase_volume_lkr: 0,
        po_count: 0,
        completed_po_count: 0,
        on_time_count: 0,
        total_observed_lead_time_days: 0,
        lead_time_count: 0,
      }
    })

    ;(purchases || []).forEach(po => {
      const sid = po.supplier_id
      if (!supplierMap[sid]) return

      supplierMap[sid].total_purchase_volume_lkr += Number(po.total_amount) || 0
      supplierMap[sid].po_count += 1

      if (po.status === 'received' || po.status === 'completed') {
        supplierMap[sid].completed_po_count += 1

        if (po.received_at && po.created_at) {
          const received = new Date(po.received_at)
          const created = new Date(po.created_at)
          const leadDays = (received - created) / (1000 * 60 * 60 * 24)
          if (leadDays >= 0) {
            supplierMap[sid].total_observed_lead_time_days += leadDays
            supplierMap[sid].lead_time_count += 1
          }
        }

        if (po.received_at && po.expected_delivery_date) {
          const received = new Date(po.received_at)
          const expected = new Date(po.expected_delivery_date)
          if (received <= expected) {
            supplierMap[sid].on_time_count += 1
          }
        }
      }
    })

    const reportData = Object.values(supplierMap).map(s => ({
      ...s,
      total_purchase_volume_lkr: Math.round(s.total_purchase_volume_lkr * 100) / 100,
      avg_observed_lead_time_days: s.lead_time_count > 0
        ? Math.round((s.total_observed_lead_time_days / s.lead_time_count) * 10) / 10
        : null,
      on_time_delivery_rate: s.completed_po_count > 0
        ? Math.round((s.on_time_count / s.completed_po_count) * 100 * 10) / 10
        : null,
      promised_lead_time_days: s.average_delivery_days,
    }))

    const summary = {
      generated_at: new Date().toISOString(),
      date_from: from.slice(0, 10),
      date_to: to.slice(0, 10),
      total_suppliers: reportData.length,
      total_purchase_volume_lkr: Math.round(reportData.reduce((s, r) => s + r.total_purchase_volume_lkr, 0) * 100) / 100,
      total_pos: reportData.reduce((s, r) => s + r.po_count, 0),
      suppliers: reportData,
    }

    if (format === 'pdf') {
      const doc = new jsPDF({ unit: 'mm', format: 'a4' })
      addReportHeader(doc, 'SUPPLIER REPORT', `${formatDate(from)} — ${formatDate(to)}`)
      let y = addKpiCards(doc, [
        { label: 'Active Suppliers', value: String(summary.total_suppliers) },
        { label: 'Total POs', value: String(summary.total_pos) },
        { label: 'Total Volume', value: formatCurrency(summary.total_purchase_volume_lkr) },
        { label: 'Period', value: `${summary.date_from} to ${summary.date_to}` },
      ], 46)

      const tableRows = reportData.map((s, i) => [
        i + 1,
        s.supplier_name,
        s.po_count,
        formatCurrency(s.total_purchase_volume_lkr),
        s.avg_observed_lead_time_days != null ? `${s.avg_observed_lead_time_days}d` : '—',
        s.on_time_delivery_rate != null ? `${s.on_time_delivery_rate}%` : '—',
      ])

      doc.autoTable({
        startY: y,
        margin: { left: 14, right: 14 },
        head: [['#', 'Supplier', 'POs', 'Volume (LKR)', 'Avg Lead Time', 'On-Time Rate']],
        body: tableRows,
        headStyles: { fillColor: [13, 17, 23], textColor: 255, fontSize: 7, fontStyle: 'bold', halign: 'center' },
        columnStyles: {
          0: { cellWidth: 8, halign: 'center' },
          1: { cellWidth: 50 },
          2: { cellWidth: 15, halign: 'center' },
          3: { cellWidth: 35, halign: 'right' },
          4: { cellWidth: 25, halign: 'center' },
          5: { cellWidth: 25, halign: 'center' },
        },
        bodyStyles: { fontSize: 7.5, textColor: [40, 40, 40] },
        alternateRowStyles: { fillColor: [250, 250, 250] },
        styles: { lineColor: [220, 220, 220], lineWidth: 0.1 },
      })

      addReportFooter(doc)
      const buf = Buffer.from(doc.output('arraybuffer'))
      res.setHeader('Content-Type', 'application/pdf')
      res.setHeader('Content-Disposition', `attachment; filename="forgera-supplier-report-${new Date().toISOString().slice(0, 10)}.pdf"`)
      return res.send(buf)
    }

    if (format === 'excel') {
      const summaryRows = [
        { label: 'Active Suppliers', value: summary.total_suppliers },
        { label: 'Total Purchase Orders', value: summary.total_pos },
        { label: 'Total Purchase Volume (LKR)', value: summary.total_purchase_volume_lkr },
        { label: 'Date Range', value: `${summary.date_from} to ${summary.date_to}` },
      ]
      const detailHeaders = ['#', 'Supplier', 'PO Count', 'Volume (LKR)', 'Avg Lead Time (Days)', 'On-Time Rate (%)']
      const detailRows = reportData.map((s, i) => [
        i + 1, s.supplier_name, s.po_count, s.total_purchase_volume_lkr,
        s.avg_observed_lead_time_days, s.on_time_delivery_rate,
      ])

      const wb = await buildWorkbook(summaryRows, detailHeaders, detailRows, 'Suppliers')
      const buf = await wb.xlsx.writeBuffer()
      res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet')
      res.setHeader('Content-Disposition', `attachment; filename="forgera-supplier-report-${new Date().toISOString().slice(0, 10)}.xlsx"`)
      return res.send(Buffer.from(buf))
    }

    res.json(summary)
  } catch (err) {
    console.error('Error generating supplier report:', err)
    res.status(500).json({ error: err.message })
  }
})

