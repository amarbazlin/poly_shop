// GET /api/reports/sales?date_from=&date_to=&format=json|pdf|excel
// ═════════════════════════════════════════════════════════════════════════════
router.get('/sales', async (req, res) => {
  const supabase = getSupabase(req)
  const { date_from, date_to, format = 'json' } = req.query
  const { from, to } = getDateRange(date_from, date_to)

  try {
    // ── Revenue recognition ──────────────────────────────────────────────────
    // A sale counts as revenue on the day the money comes in:
    //   • cash / card / bank / cheque → the sale date (created_at)
    //   • credit                      → the day it is marked paid (paid_at)
    //   • unpaid credit               → excluded until it is paid
    const recognizedAt = (sale) => sale?.paid_at || (sale?.is_credit ? null : sale?.created_at)
    const inRange = (iso) => {
      if (!iso) return false
      const t = new Date(iso).getTime()
      return t >= new Date(from).getTime() && t <= new Date(to).getTime()
    }
    const isMissingPaidAt = (e) => /paid_at/.test(String(e?.message || ''))

    const salesBase = () => {
      let q = supabase.from('sales')
      if (req.businessId) q = q.eq('business_id', req.businessId)
      return q
    }
    const salesSelect = 'id, total_amount, created_at, paid_at, is_credit'
    const [byCreated, byPaid] = await Promise.all([
      salesBase().select(salesSelect).gte('created_at', from).lte('created_at', to).order('created_at'),
      salesBase().select(salesSelect).gte('paid_at', from).lte('paid_at', to).order('created_at'),
    ])

    let sales
    if ([byCreated.error, byPaid.error].some(e => e && isMissingPaidAt(e))) {
      // sales.paid_at not migrated yet — recognise every sale on its sale date
      const legacy = await salesBase()
        .select('id, total_amount, created_at, is_credit')
        .gte('created_at', from).lte('created_at', to).order('created_at')
      if (legacy.error) throw legacy.error
      sales = (legacy.data || []).map(r => ({ ...r, paid_at: r.created_at }))
    } else {
      if (byCreated.error) throw byCreated.error
      if (byPaid.error) throw byPaid.error
      const byId = new Map()
      for (const row of [...(byCreated.data || []), ...(byPaid.data || [])]) byId.set(row.id, row)
      sales = [...byId.values()]
    }
    // Sales whose revenue lands inside the report window (unpaid credit excluded)
    const recognizedSales = sales.filter(s => inRange(recognizedAt(s)))

    const itemsSelect = `
        id, product_id, quantity, subtotal, cost_price,
        products ( id, product_name, product_code, quantity, selling_price, cost_price ),
        sale:sale_id!inner ( created_at, paid_at, is_credit, business_id )
      `
    const itemsBase = () => {
      let q = supabase.from('sales_items').select(itemsSelect).limit(5000)
      if (req.businessId) q = q.eq('sale.business_id', req.businessId)
      return q
    }
    const [itemsByCreated, itemsByPaid] = await Promise.all([
      itemsBase().gte('sale.created_at', from).lte('sale.created_at', to),
      itemsBase().gte('sale.paid_at', from).lte('sale.paid_at', to),
    ])

    let saleItems
    if ([itemsByCreated.error, itemsByPaid.error].some(e => e && isMissingPaidAt(e))) {
      // sales.paid_at not migrated yet — attribute every item to its sale date
      let legacyQuery = supabase
        .from('sales_items')
        .select(`
          id, product_id, quantity, subtotal, cost_price,
          products ( id, product_name, product_code, quantity, selling_price, cost_price ),
          sale:sale_id!inner ( created_at, business_id )
        `)
        .gte('sale.created_at', from)
        .lte('sale.created_at', to)
        .limit(5000)
      if (req.businessId) legacyQuery = legacyQuery.eq('sale.business_id', req.businessId)
      const legacyItems = await legacyQuery
      if (legacyItems.error) throw legacyItems.error
      saleItems = (legacyItems.data || []).map(it => ({
        ...it,
        sale: it.sale ? { ...it.sale, paid_at: it.sale.created_at, is_credit: false } : it.sale,
      }))
    } else {
      if (itemsByCreated.error) throw itemsByCreated.error
      if (itemsByPaid.error) throw itemsByPaid.error
      const byId = new Map()
      for (const it of [...(itemsByCreated.data || []), ...(itemsByPaid.data || [])]) byId.set(it.id, it)
      saleItems = [...byId.values()]
    }

    const trend = {}
    ;(recognizedSales || []).forEach(s => {
      const d = new Date(recognizedAt(s))
      const weekKey = `${d.getFullYear()}-W${String(Math.ceil((d.getDate() + 6 - d.getDay()) / 7)).padStart(2, '0')}`
      const weekLabel = d.toLocaleDateString('en-LK', { month: 'short', day: 'numeric' })
      if (!trend[weekKey]) trend[weekKey] = { period: weekLabel, revenue_lkr: 0, transaction_count: 0 }
      trend[weekKey].revenue_lkr += Number(s.total_amount) || 0
      trend[weekKey].transaction_count += 1
    })

    const productAgg = {}
    ;(saleItems || []).forEach(item => {
      const pid = item.product_id
      if (!pid) return
      // Product revenue/COGS only counts sales whose money has come in —
      // unpaid credit sales are excluded until they are marked paid.
      if (!inRange(recognizedAt(item.sale))) return
      if (!productAgg[pid]) {
        productAgg[pid] = {
          product_id: pid,
          product_name: item.products?.product_name || `Product #${pid}`,
          product_code: item.products?.product_code || '',
          current_stock: Number(item.products?.quantity) || 0,
          selling_price_lkr: Number(item.products?.selling_price) || 0,
          cost_price_lkr: Number(item.products?.cost_price) || 0,
          qty_sold: 0,
          revenue_lkr: 0,
          cost_lkr: 0,
        }
      }
      productAgg[pid].qty_sold += Number(item.quantity) || 0
      productAgg[pid].revenue_lkr += Number(item.subtotal) || 0
      productAgg[pid].cost_lkr += (Number(item.cost_price) || 0) * (Number(item.quantity) || 0)
    })

    const products = Object.values(productAgg)
    const topByRevenue = [...products].sort((a, b) => b.revenue_lkr - a.revenue_lkr).slice(0, 20)
    const bottomByRevenue = [...products].sort((a, b) => a.revenue_lkr - b.revenue_lkr).slice(0, 10)

    const totalRevenue = recognizedSales.reduce((s, sale) => s + (Number(sale.total_amount) || 0), 0)
    const totalTransactions = recognizedSales.length
    const totalCOGS = products.reduce((s, p) => s + p.cost_lkr, 0)
    const grossProfit = totalRevenue - totalCOGS
    const grossMarginPct = totalRevenue > 0 ? Math.round((grossProfit / totalRevenue) * 100 * 10) / 10 : 0

    const reportData = {
      generated_at: new Date().toISOString(),
      date_from: from.slice(0, 10),
      date_to: to.slice(0, 10),
      total_revenue_lkr: Math.round(totalRevenue * 100) / 100,
      total_transactions: totalTransactions,
      total_cogs_lkr: Math.round(totalCOGS * 100) / 100,
      gross_profit_lkr: Math.round(grossProfit * 100) / 100,
      gross_margin_pct: grossMarginPct,
      products_sold: products.length,
      revenue_trend: Object.entries(trend).map(([key, d]) => ({ week: key, ...d, revenue_lkr: Math.round(d.revenue_lkr * 100) / 100 })),
      top_by_revenue: topByRevenue.map(p => ({ ...p, revenue_lkr: Math.round(p.revenue_lkr * 100) / 100, cost_lkr: Math.round(p.cost_lkr * 100) / 100 })),
      bottom_by_revenue: bottomByRevenue.map(p => ({ ...p, revenue_lkr: Math.round(p.revenue_lkr * 100) / 100, cost_lkr: Math.round(p.cost_lkr * 100) / 100 })),
      product_performance: products.map(p => ({
        product_id: p.product_id,
        product_name: p.product_name,
        product_code: p.product_code,
        units_sold: p.qty_sold,
        revenue_lkr: Math.round(p.revenue_lkr * 100) / 100,
        margin_lkr: Math.round((p.revenue_lkr - p.cost_lkr) * 100) / 100,
      })),
    }

    if (format === 'pdf') {
      const doc = new jsPDF({ unit: 'mm', format: 'a4' })
      addReportHeader(doc, 'SALES REPORT', `${formatDate(from)} — ${formatDate(to)}`)
      let y = addKpiCards(doc, [
        { label: 'Total Revenue', value: formatCurrency(totalRevenue) },
        { label: 'Transactions', value: String(totalTransactions) },
        { label: 'Gross Profit', value: formatCurrency(grossProfit) },
        { label: 'Margin', value: `${grossMarginPct}%` },
      ], 46)

      doc.setFontSize(8)
      doc.setFont('helvetica', 'bold')
      doc.setTextColor(13, 17, 23)
      doc.text('Top Sellers by Revenue', 14, y)
      y += 4

      const topRows = topByRevenue.slice(0, 10).map((p, i) => [
        i + 1, p.product_name, p.qty_sold, formatCurrency(p.revenue_lkr),
      ])

      doc.autoTable({
        startY: y,
        margin: { left: 14, right: 14 },
        head: [['#', 'Product', 'Qty Sold', 'Revenue (LKR)']],
        body: topRows,
        headStyles: { fillColor: [13, 17, 23], textColor: 255, fontSize: 7, fontStyle: 'bold', halign: 'center' },
        columnStyles: {
          0: { cellWidth: 8, halign: 'center' },
          1: { cellWidth: 60 },
          2: { cellWidth: 15, halign: 'center' },
          3: { cellWidth: 35, halign: 'right' },
        },
        bodyStyles: { fontSize: 7.5, textColor: [40, 40, 40] },
        alternateRowStyles: { fillColor: [250, 250, 250] },
        styles: { lineColor: [220, 220, 220], lineWidth: 0.1 },
      })

      y = doc.lastAutoTable.finalY + 8

      doc.setFontSize(8)
      doc.setFont('helvetica', 'bold')
      doc.setTextColor(13, 17, 23)
      doc.text('Bottom Sellers by Revenue', 14, y)
      y += 4

      const bottomRows = bottomByRevenue.slice(0, 10).map((p, i) => [
        i + 1, p.product_name, p.qty_sold, formatCurrency(p.revenue_lkr),
      ])

      doc.autoTable({
        startY: y,
        margin: { left: 14, right: 14 },
        head: [['#', 'Product', 'Qty Sold', 'Revenue (LKR)']],
        body: bottomRows,
        headStyles: { fillColor: [13, 17, 23], textColor: 255, fontSize: 7, fontStyle: 'bold', halign: 'center' },
        columnStyles: {
          0: { cellWidth: 8, halign: 'center' },
          1: { cellWidth: 60 },
          2: { cellWidth: 15, halign: 'center' },
          3: { cellWidth: 35, halign: 'right' },
        },
        bodyStyles: { fontSize: 7.5, textColor: [40, 40, 40] },
        alternateRowStyles: { fillColor: [250, 250, 250] },
        styles: { lineColor: [220, 220, 220], lineWidth: 0.1 },
      })

      addReportFooter(doc)
      const buf = Buffer.from(doc.output('arraybuffer'))
      res.setHeader('Content-Type', 'application/pdf')
      res.setHeader('Content-Disposition', `attachment; filename="forgera-sales-report-${new Date().toISOString().slice(0, 10)}.pdf"`)
      return res.send(buf)
    }

    if (format === 'excel') {
      const summaryRows = [
        { label: 'Total Revenue (LKR)', value: totalRevenue },
        { label: 'Total Transactions', value: totalTransactions },
        { label: 'Total COGS (LKR)', value: totalCOGS },
        { label: 'Gross Profit (LKR)', value: grossProfit },
        { label: 'Gross Margin (%)', value: grossMarginPct },
        { label: 'Products Sold', value: products.length },
        { label: 'Date Range', value: `${reportData.date_from} to ${reportData.date_to}` },
      ]
      const detailHeaders = ['#', 'Product', 'Qty Sold', 'Revenue (LKR)', 'Cost (LKR)']
      const detailRows = topByRevenue.map((p, i) => [
        i + 1, p.product_name, p.qty_sold, p.revenue_lkr, p.cost_lkr,
      ])

      const wb = await buildWorkbook(summaryRows, detailHeaders, detailRows, 'Sales')
      const buf = await wb.xlsx.writeBuffer()
      res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet')
      res.setHeader('Content-Disposition', `attachment; filename="forgera-sales-report-${new Date().toISOString().slice(0, 10)}.xlsx"`)
      return res.send(Buffer.from(buf))
    }

    res.json(reportData)
  } catch (err) {
    console.error('Error generating sales report:', err)
    res.status(500).json({ error: err.message })
  }
})

